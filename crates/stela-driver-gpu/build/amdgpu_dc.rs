/// supplied: devres groups and `ktime_get_raw` by Stela's Linux runtime,
/// `kernel_fpu_begin_mask`/`kernel_fpu_end` by its `fpu.c`, and the DSC,
/// HDCP and panel backlight quirk helpers by the DRM environment. Its only
/// trap, `backlight_device_register` for eDP and LVDS panels, is already
/// open for the DCE encoders.
