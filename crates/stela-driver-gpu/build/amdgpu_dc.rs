//! amdgpu's Display Core: `AMD_DISPLAY_FILES`, which amdgpu's makefile adds
//! to `amdgpu-y` under `CONFIG_DRM_AMD_DC`, as GNU make evaluates
//! `display/Makefile` and the `DAL_LIBS` makefiles it includes with
//! `CONFIG_DRM_AMD_DC` and `CONFIG_DRM_AMD_DC_FP` set and `CONFIG_DEBUG_FS`,
//! `CONFIG_DRM_AMD_DC_SI` and `CONFIG_DRM_AMD_DC_KUNIT_TEST` not. The DML
//! makefiles list some objects more than once; kbuild links each once, and
//! [`OBJECTS`] lists each once.
//!
//! Linux compiles the objects in [`FPU`] with `CC_FLAGS_FPU` (x86's `-msse
//! -msse2`) and removes `CC_FLAGS_NO_FPU` from them; Stela's native C is
//! `-mgeneral-regs-only`, so they are compiled with `-msse -msse2` after it,
//! which clang applies in order: SSE and SSE2 return, x87 stays off as under
//! Linux's `-mno-80387`. Each runs only between `DC_FP_START` and
//! `DC_FP_END`, whose `kernel_fpu_begin` saves the caller's extended state
//! (see `stela-linux/src/compat/kernel/fpu.c`).
