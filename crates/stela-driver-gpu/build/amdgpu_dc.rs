/// Every object word of the display makefiles is listed or excluded, every
/// listed or excluded object is a word of theirs, every listed object has a
/// source, and every FPU object is listed.
pub fn check_objects(amd: &Path) {
    let mut words = BTreeSet::new();
    for makefile in MAKEFILES {
        let path = amd.join(makefile);
        println!("cargo:rerun-if-changed={}", path.display());
        let text =
            fs::read_to_string(&path).unwrap_or_else(|error| panic!("{}: {error}", path.display()));
        for word in text.split(|c: char| c.is_whitespace() || matches!(c, '\\' | ',' | '(' | ')')) {
            // `$(NAME).o` and pattern rules' `%.o` name no object themselves.
            if let Some(object) = word.strip_suffix(".o") {
                let object = object.rsplit('/').next().unwrap_or(object);
                if !object.is_empty() && object != "%" {
                    words.insert(object.to_owned());
                }
            }
        }
    }
    let listed = OBJECTS
        .iter()
        .map(|object| object.rsplit('/').next().unwrap_or(object))
        .collect::<BTreeSet<_>>();
    assert_eq!(listed.len(), OBJECTS.len(), "a DC object is listed twice");
    let excluded = EXCLUDED
        .iter()
        .flat_map(|(_, objects)| objects.iter().copied())
        .collect::<BTreeSet<_>>();
    for word in &words {
        assert!(
            listed.contains(word.as_str()) || excluded.contains(word.as_str()),
            "the display makefiles name {word}.o, which is neither listed nor excluded"
        );
    }
    for object in listed.iter().chain(&excluded) {
        assert!(
            words.contains(*object),
            "{object}.o is listed or excluded, but no display makefile names it"
        );
    }
    for object in OBJECTS {
        let source = amd.join(object).with_extension("c");
        assert!(source.is_file(), "{} is missing", source.display());
    }
    for object in FPU {
        assert!(
            OBJECTS.contains(object),
            "FPU object {object} is not listed"
        );
    }
}

